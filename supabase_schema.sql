-- 9. RPC Functions (Dashboard Data)
create or replace function get_home_dashboard()
returns json as $$
declare
  active_participants int;
  latest_surveys json;
  next_lottery_draw json;
begin
  -- 1. Get today's active participants (unique voters today)
  -- Approximation based on recent profile updates or votes
  select count(distinct user_id) into active_participants
  from survey_votes
  where created_at > current_date;
  
  -- If null (no votes), default to 0
  if active_participants is null then
    active_participants := 0;
  end if;

  -- 2. Get latest 2 active surveys
  select json_agg(t) into latest_surveys
  from (
    select id, title, category, created_at
    from surveys
    where is_active = true
    order by created_at desc
    limit 2
  ) t;

  -- 3. Get next lottery draw (first 'open' round)
  select row_to_json(r) into next_lottery_draw
  from (
    select id, round_number, draw_date, total_prize_pool
    from lottery_rounds
    where status = 'open'
    order by draw_date asc
    limit 1
  ) r;

  return json_build_object(
    'active_participants', active_participants,
    'latest_surveys', coalesce(latest_surveys, '[]'::json),
    'next_lottery_draw', next_lottery_draw
  );
end;
$$ language plpgsql security definer;


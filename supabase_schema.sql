-- Trigger to update likes_count
create or replace function update_politician_likes()
returns trigger as $$
begin
  if (TG_OP = 'INSERT') then
    update politicians set likes_count = likes_count + 1 where id = new.politician_id;
    return new;
  elsif (TG_OP = 'DELETE') then
    update politicians set likes_count = likes_count - 1 where id = old.politician_id;
    return old;
  end if;
  return null;
end;
$$ language plpgsql security definer;

create trigger on_politician_like
  after insert or delete on politician_likes
  for each row execute procedure update_politician_likes();



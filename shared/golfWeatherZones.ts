export interface WxZone { key: string; ta: string; lat: number; lng: number }
const ALL: WxZone[] = Object.entries(WX_ZONES).map(([key, [ta, lat, lng]]) => ({ key, ta, lat, lng }));

/**
 * 시군이 아닌 산지 구역 — 이 지점에서 가까운(EXTRA_KM) 골프장은 시군 대신 이 구역의 기온을 쓴다.
 * 대관령: 용평·알펜시아·버치힐은 평창군이지만 평창읍(중기 최고 25°)과 10월 낮 기온이 4° 넘게 다르다(대관령 21°, 그 격자의 단기예보 19°).
 */
const EXTRA: WxZone[] = [{ key: "강원|대관령", ta: "11D20201", lat: 37.6771, lng: 128.7183 }];
const EXTRA_KM = 12;

/** 골프장 좌표가 시군 중심에서 이만큼 넘게 떨어져 있으면 좌표가 틀린 것으로 본다(평창 대관령·홍천 서면이 40km 남짓 — 그보다 넉넉히). */
export const WX_SUSPECT_KM = 60;

/** 그 골프장의 구역. 표에 없는 시군(또는 시군이 빈 골프장)은 좌표에서 가장 가까운 구역. */
export function zoneFor(p: { region?: string | null; city?: string | null; lat?: number | null; lng?: number | null }): WxZone | null {
    if (p.lat != null && p.lng != null) for (const z of EXTRA) if (distanceKm({ lat: p.lat, lng: p.lng }, z) <= EXTRA_KM) return z;
    const hit = p.region && p.city ? WX_ZONES[`${p.region}|${p.city}`] : undefined;
    if (hit) return { key: `${p.region}|${p.city}`, ta: hit[0], lat: hit[1], lng: hit[2] };
    if (p.lat == null || p.lng == null) return null;
    let best: WxZone | null = null, bestD = Infinity;
    for (const z of ALL) { const d = distanceKm({ lat: p.lat, lng: p.lng }, z); if (d < bestD) { best = z; bestD = d; } }
    return best;
}

/**
 * 날씨를 볼 지점. 골프장 좌표가 먼저고, 없거나(28곳) 시군에서 터무니없이 멀면(좌표 오류 4곳 — 150km 넘게 어긋나 있다)
 * 시군 중심으로 잡고 approx 로 알린다. 틀린 곳의 날씨를 그럴듯하게 보여 주느니 "○○시 기준"이라고 말하는 쪽이 낫다.
 */
export function weatherPoint(p: { region?: string | null; city?: string | null; lat?: number | null; lng?: number | null }): { lat: number; lng: number; zone: WxZone; approx: boolean } | null {
    const zone = zoneFor(p);
    if (!zone) return null;
    if (p.lat != null && p.lng != null && distanceKm({ lat: p.lat, lng: p.lng }, zone) <= WX_SUSPECT_KM) return { lat: p.lat, lng: p.lng, zone, approx: false };
    return { lat: zone.lat, lng: zone.lng, zone, approx: true };
}

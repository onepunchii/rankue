const NONE: readonly LocalDish[] = [];
/** 그 시군의 대표 메뉴 — 없으면 빈 목록(지어내지 않는다) */
export function localDishes(region: string | null | undefined, city: string | null | undefined): readonly LocalDish[] {
    if (!region || !city) return NONE;
    return Object.prototype.hasOwnProperty.call(LOCAL_DISHES, `${region}|${city}`) ? LOCAL_DISHES[`${region}|${city}`] : NONE;
}
/** 손님이 보낸 낱말이 그 시군의 대표 메뉴일 때만 돌려준다 — 아무 말이나 검색어로 받지 않는다 */
export function findLocalDish(region: string | null | undefined, city: string | null | undefined, word: unknown): LocalDish | null {
    if (typeof word !== "string" || !word) return null;
    const w = word.normalize("NFC");
    return localDishes(region, city).find((x) => x.word === w) ?? null;
}
/** 칩 줄의 이름표이자 검색엔진용 화면의 제목 — "춘천 대표 메뉴" */
export const localDishLabel = (city: string | null | undefined): string => `${cityShort(city)} 대표 메뉴`;
/** 검색엔진용 화면의 한 줄 — "🍗 닭갈비 · 🍜 막국수"(화면의 칩과 같은 글) */
export const localDishLine = (dishes: readonly LocalDish[]): string => dishes.map((x) => `${x.emoji} ${x.word}`).join(" · ");

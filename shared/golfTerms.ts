export type GolfTermCategory = "score" | "course" | "shot" | "rule" | "round" | "format";

export interface GolfTermPage {
    meaning: string;
    usage: string;
    example: string;
    confusion: string;
    /** 랭큐 골프에서 이 말이 어떻게 쓰이는지 — 실제 기능만 */
    inApp?: string;
}

export interface GolfTerm {
    slug: string;
    term: string;
    emoji: string;
    aliases?: string[];
    category: GolfTermCategory;
    /** 한 줄 정의 — 허브 목록·meta description·DefinedTerm.description 공용 */
    short: string;
    page?: GolfTermPage;
    related?: string[];
    links?: { href: string; label: string }[];
}


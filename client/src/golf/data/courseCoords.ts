/** 골프장 id 로 좌표를 찾는다. 없으면 null — 부르는 쪽이 거리를 안 그린다. */
export function courseCoord(courseId: unknown): { lat: number; lng: number } | null {
    const id = Number(courseId);
    if (!Number.isFinite(id)) return null;
    const p = COURSE_COORDS[id];
    return p ? { lat: p[0], lng: p[1] } : null;
}
